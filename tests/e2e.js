async function newPage(browser, opts = {}) {
  const ctx = await browser.newContext(Object.assign({
    viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true,
    userAgent: 'Mozilla/5.0 (Linux; Android 14; Pixel 8) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Mobile Safari/537.36',
    acceptDownloads: true, timezoneId: 'Asia/Kuala_Lumpur', locale: 'ms-MY'
  }, opts));
  const page = await ctx.newPage();
  page.errors = [];
  page.on('console', m => { if (m.type() === 'error' && !/fonts\.g|ERR_FAILED|net::/.test(m.text())) page.errors.push(m.text()); });
  page.on('pageerror', e => page.errors.push(e.message));
  await page.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
  page.waHits = [];
  await page.route(/wa\.me|whatsapp\.com/, r => { page.waHits.push(decodeURIComponent(r.request().url())); r.fulfill({ status: 204, body: '' }); });
  await page.clock.setFixedTime(new Date('2026-10-28T09:20:00+08:00'));
  return { ctx, page };
}
